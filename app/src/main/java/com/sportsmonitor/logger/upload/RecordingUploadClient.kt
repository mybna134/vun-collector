package com.sportsmonitor.logger.upload

import java.io.File
import java.io.IOException
import java.net.SocketTimeoutException
import java.net.URL
import java.security.MessageDigest
import com.sportsmonitor.logger.auth.ApiSigner
import com.sportsmonitor.logger.auth.apiFailure
import com.sportsmonitor.logger.auth.hex
import com.sportsmonitor.logger.auth.token
import com.sportsmonitor.logger.auth.wireQuote
import java.util.concurrent.TimeUnit
import okhttp3.MediaType.Companion.toMediaType
import okhttp3.OkHttpClient
import okhttp3.Request
import okhttp3.RequestBody
import okio.BufferedSink
import java.util.UUID
import org.json.JSONObject

data class RecordingUploadResult(val jsonUUID: String)

class RecordingUploadClient(
    private val signer: ApiSigner,
    private val endpoint: URL = URL("https://api.myb666.ccwu.cc/route-templates"),
) {
    companion object {
        const val MAX_REQUEST_BYTES = 100_000_000L
        private val http = OkHttpClient.Builder()
            .connectTimeout(15, TimeUnit.SECONDS)
            .readTimeout(60, TimeUnit.SECONDS)
            .writeTimeout(60, TimeUnit.SECONDS)
            .retryOnConnectionFailure(false)
            .followRedirects(false)
            .followSslRedirects(false)
            .build()

        fun normalizeTemplateName(value: String): String = value.trim().also { name ->
            require(name.length in 1..255) { "模板名称须为 1–255 个字符" }
            require(name.none { it.code in 0..31 || it.code == 127 }) { "模板名称不能包含控制字符" }
        }
    }

    /** The file is generated by RecordingExporter; stream it as an object, not a JSON string. */
    fun upload(jsonFile: File, accessToken: String, templateName: String, checkCancelled: () -> Unit = {}): RecordingUploadResult {
        val name = normalizeTemplateName(templateName)
        val authorization = "Bearer ${token(accessToken)}"
        require(jsonFile.isFile && jsonFile.length() > 0L) { "上传的 JSON 文件为空" }
        val prefix = "{\"routeTemplateName\":${wireQuote(name)},\"route-template-json\":".toByteArray(Charsets.UTF_8)
        val size = prefix.size + jsonFile.length() + 1L
        require(size <= MAX_REQUEST_BYTES) { "JSON 加上模板名称及包装字段后超过 100 MB，无法上传" }
        checkCancelled()
        val digest = MessageDigest.getInstance("SHA-256")
        digest.update(prefix)
        jsonFile.inputStream().use { input ->
            val buffer = ByteArray(DEFAULT_BUFFER_SIZE)
            while (true) {
                checkCancelled()
                val count = input.read(buffer)
                if (count < 0) break
                digest.update(buffer, 0, count)
            }
        }
        digest.update('}'.code.toByte())
        val signed = signer.headers("PUT", endpoint, digest.digest().hex(), authorization)
        checkCancelled()
        val body = object : RequestBody() {
            override fun contentType() = "application/json; charset=utf-8".toMediaType()
            override fun contentLength() = size
            override fun isOneShot() = true
            override fun writeTo(sink: BufferedSink) {
                sink.write(prefix)
                jsonFile.inputStream().use { input ->
                    val buffer = ByteArray(DEFAULT_BUFFER_SIZE)
                    while (true) {
                        checkCancelled()
                        val count = input.read(buffer)
                        if (count < 0) break
                        sink.write(buffer, 0, count)
                    }
                }
                sink.writeByte('}'.code)
            }
        }
        val request = Request.Builder().url(endpoint).put(body)
            .header("Accept", "application/json")
            .header("Authorization", authorization)
            .header("tick", signed.tick)
            .header("sign", signed.sign)
            .build()
        try {
            return http.newCall(request).execute().use { response ->
                checkCancelled()
                val text = response.body?.string().orEmpty()
                if (response.code != 201) throw apiFailure(response.code, text)
                try {
                    val json = JSONObject(text)
                    RecordingUploadResult(UUID.fromString(json.getString("jsonUUID")).toString())
                } catch (error: Exception) {
                    throw IllegalStateException("服务端已接收上传，但返回结果无法解析，请确认后再重试", error)
                }
            }
        } catch (error: SocketTimeoutException) {
            throw IOException("上传超时，结果未确认，请确认后再重试", error)
        } catch (error: IOException) {
            throw IOException("上传连接异常，结果未确认，请确认后再重试", error)
        }
    }
}
